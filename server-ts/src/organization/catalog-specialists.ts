import type { RoleSpec } from './catalog.ts';

/**
 * The rest of the specialist catalogue (catalog 30): enough roles that every
 * department offers eight. Each is a specialist, so a workspace has it only
 * when a person adds it. Roles that build or run software are level 3 and
 * are reviewed like any code; everyone else is level 2 — they write documents
 * and tasks, run no commands, and a person releases their work.
 */

type Draft = Omit<RoleSpec, 'tier' | 'level' | 'code' | 'reviewDomains' | 'delegates'> &
   Partial<Pick<RoleSpec, 'tier' | 'level' | 'code' | 'delegates'>>;

function specialist(draft: Draft): RoleSpec {
   return { tier: 'berry_low', level: 2, code: false, delegates: [], reviewDomains: [], ...draft };
}

/** A role that writes and runs code: level 3, reviewed by the Reviewer. */
function engineer(draft: Draft): RoleSpec {
   return specialist({ level: 3, code: true, ...draft });
}

